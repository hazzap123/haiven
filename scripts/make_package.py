#!/usr/bin/env python3
"""Build Haiven as one self-contained Home Assistant package file.

For a Home Assistant config that already loads a packages folder
(`packages: !include_dir_merge_named packages/`) or splits automations and
scripts across files. Merging Haiven's configuration.yaml into such a config
by hand breaks it: the package files are bare domain dictionaries, and its
own top-level blocks collide with yours. This writes everything Haiven needs
into one file of named packages, so the install is a copy, not a merge:

    python3 scripts/make_package.py --out haiven.yaml
    # copy haiven.yaml into /config/packages/

Run it in your clone after scripts/setup.sh, so your sensor IDs are in it.

What it leaves to you, because a package cannot hold it (printed at the end):
  - homeassistant: allowlist_external_dirs and media_dirs, for the optional
    camera, in your configuration.yaml, and the folder they point at;
  - the files the package refers to: www/, lovelace/, scripts/*.py and *.sh,
    themes/haiven*.yaml.
Haiven's `http:` block (development origins) and `default_config:` are left
out: your configuration.yaml already decides those.
"""
import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIP = {"default_config", "http", "homeassistant", "scene", "frontend",
        "automation", "script"}


class Loader(yaml.SafeLoader):
    pass


def _include(loader, node):
    path = ROOT / loader.construct_scalar(node)
    return yaml.load(path.read_text(), Loader=Loader)


Loader.add_constructor("!include", _include)
# themes: !include_dir_merge_named themes is your frontend's job, not ours.
Loader.add_constructor("!include_dir_merge_named", lambda loader, node: None)


class Dumper(yaml.SafeDumper):
    pass


def _str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, _str)


def build():
    cfg = yaml.load((ROOT / "configuration.yaml").read_text(), Loader=Loader)
    packages = dict(cfg["homeassistant"]["packages"])
    core = {k: v for k, v in cfg.items() if k not in SKIP}
    core["frontend"] = {"extra_module_url": list(cfg["frontend"]["extra_module_url"])}
    core["automation"] = yaml.safe_load((ROOT / "automations.yaml").read_text()) or []
    core["script"] = yaml.safe_load((ROOT / "scripts.yaml").read_text()) or {}
    for name in packages:
        if "homeassistant" in (packages[name] or {}):
            sys.exit(f"package {name} holds core config; it cannot be packaged")
    return {"haiven_core": core, **packages}


HEADER = """\
# Haiven, as one Home Assistant package file. Generated by
# scripts/make_package.py from the Haiven repository; do not edit by hand,
# regenerate instead. Copy into the folder your configuration.yaml loads with
#   homeassistant:
#     packages: !include_dir_merge_named packages/
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default="haiven.yaml")
    args = ap.parse_args()
    data = build()
    text = HEADER + yaml.dump(data, Dumper=Dumper, sort_keys=False,
                              allow_unicode=True, width=1000)
    pathlib.Path(args.out).write_text(text)
    autos = len(data["haiven_core"]["automation"])
    print(f"Wrote {args.out}: {len(data)} packages, {autos} automations.")
    print("""
Also, by hand:
  1. Copy into /config: www/haiven-*.js (from www-src via setup.sh),
     lovelace/, scripts/*.py and scripts/*.sh (not setup.sh), and
     themes/haiven*.yaml into your themes folder.
  2. Only if you will use the optional camera: create /config/haiven_snapshots
     and add to homeassistant: in configuration.yaml
       allowlist_external_dirs: [/config/haiven_snapshots]
       media_dirs: {haiven: /config/haiven_snapshots}
     Home Assistant rejects the core config if that folder does not exist.
  3. Check the config, then restart.""")


if __name__ == "__main__":
    main()
